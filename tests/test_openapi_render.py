def test_reserved_param_names_renamed():
    op = _op(
        "doThing",
        "do_thing",
        "/thing",
        "/thing",
        "Do thing",
        ["ops"],
        [
            ParamModel(name="ctx", py_type="str", required=False, location="query"),
            ParamModel(name="query", py_type="str", required=False, location="query"),
            ParamModel(name="class", py_type="str", required=False, location="body"),
        ],
    )
    files = render_openapi_tools("api", [op], generator_version="1.0.0", locator="test")
    mod = files["src/tools/api/ops.py"]
    ast.parse(mod)  # must compile
    assert "ctx_: str" in mod
    assert "query_: str" in mod
    assert "class_: str" in mod
    assert 'query["ctx"]' in mod
    assert 'query["query"]' in mod
    assert 'body["class"]' in mod


