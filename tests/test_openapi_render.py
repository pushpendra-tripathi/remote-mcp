def test_duplicate_func_names_deduped():
    op1 = _op("listThingsA", "list_things", "/a", "/a", "List A", ["dup"], [])
    op2 = _op("listThingsB", "list_things", "/b", "/b", "List B", ["dup"], [])
    files = render_openapi_tools("api", [op1, op2], generator_version="1.0.0", locator="test")
    mod = files["src/tools/api/dup.py"]
    tree = ast.parse(mod)  # must compile
    func_names = {n.name for n in ast.walk(tree) if isinstance(n, ast.AsyncFunctionDef)}
    assert {"list_things", "list_things_2"} <= func_names


